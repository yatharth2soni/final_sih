export function t(key, lang = "en", fallback = "") {
  const dict = i18n[lang] || i18n.en;
  return dict[key] || i18n.en[key] || fallback || key;
}

/**
 * Statutory Status Badge Translator
 */
export function translateStatus(status, lang = "en") {
  if (lang !== "hi") return status;
  switch (status) {
    case "Compliant":
      return "अनुपालित";
    case "Due Soon":
      return "शीघ्र देय";
    case "Overdue":
      return "अतिदेय";
    case "Non-Compliant":
      return "गैर-अनुपालित";
    case "Open":
      return "खुला";
    case "In Progress":
      return "प्रगति पर";
    case "Under Review":
      return "समीक्षाधीन";
    case "Closed":
      return "बंद";
    case "PENDING_SYNC":
      return "सिंक लंबित";
    case "SYNCED":
      return "सिंक किया गया";
    default:
      return status;
  }
}